let lang = (() => {
  try { return localStorage.getItem('ht_lang') || 'uz'; }
  catch { return 'uz'; }
})();

function t(key, vars) {
  const dict = I18N[lang] || I18N.uz;
  let s = dict[key];
  if (s == null) s = I18N.en[key];
  if (s == null) s = key;
  if (vars && typeof s === 'string') {
    s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  }
  return s;
}

function localeOf() {
  return (I18N[lang] || I18N.uz).locale || 'en-GB';
}

